		$created = 0;
		foreach($defaults as $tpl){
			$exists = $this->db->where('store_id', $storeId)->where('template_key', $tpl['template_key'])->count_all_results($this->table);
			if($exists == 0){
				$tpl['store_id'] = $storeId;
				$this->create($tpl);
				$created++;
			}
		}

		// Upgrade built-in storefront templates to the current branded copy,
		// but only when the merchant has never edited them (create() stamps
		// both timestamps; the admin editor bumps updated_at).
		$storefrontKeys = [
			'online_order_owner', 'online_order_customer',
			'appointment_request_owner', 'appointment_request_customer',
			'staff_invite',
		];
		foreach($defaults as $tpl){
			if(!in_array($tpl['template_key'], $storefrontKeys)) continue;
			$row = $this->getByKey($tpl['template_key'], $storeId);
			if(!$row || $row->html_body === $tpl['html_body']) continue;
			if(!empty($row->updated_at) && $row->updated_at !== $row->created_at) continue;
